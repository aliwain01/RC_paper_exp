def fig_fairness(paths: Paths, plt, best: dict, synthetic: bool):
    """Flag rate ÷ positive rate by provider attribute at k = 1 %; the reference line is the same ratio over all
    scored providers (k ÷ base rate), i.e. flags allocated in proportion to positives."""
    fa = evaluate.load_part(paths, "fairness") or {}
    names = {"ent_cd": "entity type", "ruca_class": "RUCA class", "census_division": "Census division"}
    rows = [r for r in (fa.get("families") or {}).get(best.get("gbm"), []) if float(r["k"]) == 0.01
            and r["attribute"] in names]
    attrs = [a for a in names if any(r["attribute"] == a for r in rows)]
    if not attrs:
        return None
    sizes = [sum(r["attribute"] == a for r in rows) for a in attrs]
    fig, axes = plt.subplots(len(attrs), 1, figsize=(5.6, 0.32 * sum(sizes) + 0.9 * len(attrs)), sharex=True,
                             squeeze=False, gridspec_kw={"height_ratios": sizes})
    for ax, at in zip(axes[:, 0], attrs):
        rs = sorted((r for r in rows if r["attribute"] == at), key=lambda r: str(r["value"]))
        v = [r["flag_to_positive_ratio"] if r["flag_to_positive_ratio"] is not None else np.nan for r in rs]
        y = np.arange(len(rs))
        ax.barh(y, v, height=0.6, color=SERIES[0], zorder=3)
        N, F, P = (sum(r[c] for r in rs) for c in ("N", "flagged", "positives"))
        if P:
            ref = (F / N) / (P / N)
            ax.axvline(ref, color=INK2, linewidth=1.2, zorder=4)
            ax.text(ref, len(rs) - 0.4, " all providers", color=INK2, fontsize=8, va="bottom")
        ax.set_yticks(y, [str(r["value"]).replace("_", " ") for r in rs])
        ax.set_ylim(len(rs) - 0.4, -0.6)
        ax.grid(axis="y", visible=False)
        ax.set_title(names[at], loc="left")
    axes[-1, 0].set_xlabel(f"flag rate ÷ positive rate at k = 1 % ({best.get('gbm')})")
    fig.tight_layout()
    return fig


