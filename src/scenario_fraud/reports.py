TEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "$": r"\$", "{": r"\{",
       "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "Δ": r"$\Delta$", "ρ": r"$\rho$",
       "τ": r"$\tau$", "²": r"$^2$", "↓": r"$\downarrow$", "·": r"$\cdot$", "–": "--", "—": "---", "−": "$-$",
       "÷": r"$\div$", "≥": r"$\geq$"}


def _tex(s) -> str:
    return "".join(TEX.get(ch, ch) for ch in ("" if s is None else str(s)))


def write_table(paths: Paths, name: str, title: str, rows: list[dict], note: str = "") -> dict:
    d = tables_dir(paths)
    d.mkdir(parents=True, exist_ok=True)
    cols = list(rows[0]) if rows else []
    banner = qa.provenance_lines(qa.data_provenance(paths))
    (d / f"{name}.md").write_text("\n".join([f"**{title}**", "", *banner, qa.md_table(rows), note, ""]), encoding="utf-8")
    with open(d / f"{name}.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)
    tex = [f"% {title}", "% " + (" ".join(banner).replace("\n", " ") or "generated by scenario-fraud phase7 tables"),
           r"\begin{tabular}{" + "l" * len(cols) + "}", r"\hline",
           " & ".join(_tex(c) for c in cols) + r" \\", r"\hline"]
    tex += [" & ".join(_tex(r.get(c)) for c in cols) + r" \\" for r in rows]
    tex += [r"\hline", r"\end{tabular}", ""]
    (d / f"{name}.tex").write_text("\n".join(tex), encoding="utf-8")
    return {"name": name, "rows": len(rows)}


def t1_rows(paths: Paths) -> list[dict]:
    g3p = paths.phase3 / "G3_report.json"
    if not g3p.is_file():
        return []
    prim = json.loads(g3p.read_text(encoding="utf-8")).get("designs", {}).get("primary")
    if not prim:
        return []
    ev = load_config("experiment", paths)["evaluation"]
    fmt = eval_report.fmt
    rows = []
    for f, v in prim["t1"].items():
        p, ci = v["point"]["pooled"], v.get("ci") or {}

        def cell(m):
            return fmt(p.get(m)) + (f" [{fmt(ci[m]['ci'][0])}, {fmt(ci[m]['ci'][1])}]" if m in ci else "")
        rows.append({"Model": f, "PR-AUC": cell("pr_auc"), "ROC-AUC": fmt(p["roc_auc"]),
                     **{f"P@{float(k):.1%}": cell(f"p@{k}") for k in ev["k_fracs"]},
                     f"R@{float(ev['primary_k']):.0%}": fmt(p.get(f"r@{ev['primary_k']}")), "Brier": fmt(p.get("brier"), 5)})
    d = prim.get("delta")
    if d:
        b = d["bootstrap"]
        rows.append({"Model": f"Δ {d['a']} − {d['b']}",
                     "PR-AUC": f"{fmt(b['pr_auc']['delta'])} [{fmt(b['pr_auc']['delta_ci'][0])}, {fmt(b['pr_auc']['delta_ci'][1])}]",
                     "ROC-AUC": "", **{f"P@{float(k):.1%}": f"{fmt(b[f'p@{k}']['delta'])} [{fmt(b[f'p@{k}']['delta_ci'][0])}, "
                                                            f"{fmt(b[f'p@{k}']['delta_ci'][1])}]" for k in ev["k_fracs"]},
                     f"R@{float(ev['primary_k']):.0%}": "", "Brier": ""})
    return rows


def sensitivity_rows(paths: Paths, best: dict) -> list[dict]:
    fmt = eval_report.fmt
    rows = []
    for vid, r in sensitivity.load_results(paths).items():
        fam = best.get("gbm")
        det, det0 = (r.get("detection") or {}).get(fam), (r.get("detection_main") or {}).get(fam)
        ag = next((a for a in r.get("agreement_with_main", []) if a["family"] == fam and a["method"] == "B"), None)
        co = next((c for c in r.get("correctness", []) if c["family"] == fam and c["method"] == "B"), None)
        cs = next((c for c in r.get("consistency", []) if c["gbm"] == fam and c["method"] == "B"), None)
        what = r.get("what") if not r.get("not_estimable") else f"{r.get('what')} (not estimable: {r['not_estimable']})"
        rows.append({"Variant": vid, "Description": what,
                     "PR-AUC (variant)": fmt(det["pr_auc"]) if det else "–",
                     "PR-AUC (main)": fmt(det0["pr_auc"]) if det0 else "–",
                     "Top-1 agree with main (B)": fmt(ag["top1_agreement"]) if ag else "–",
                     "Share cos vs glass box (B)": fmt(cs["cosine"]) if cs else "–",
                     "Top-1 injected (B)": fmt(co["top1"]) if co else "–"})
    return rows


def fairness_rows(paths: Paths, best: dict) -> list[dict]:
    fa = evaluate.load_part(paths, "fairness") or {}
    fam = best.get("gbm")
    fmt = eval_report.fmt
    return [{"Attribute": r["attribute"], "Value": r["value"], "k": f"{float(r['k']):.1%}", "N": r["N"],
             "Positives": r["positives"], "Flagged": r["flagged"], "Flag rate": fmt(r["flag_rate"], 4),
             "Precision": fmt(r["precision"]), "Flag ÷ positive rate": fmt(r["flag_to_positive_ratio"], 2)}
            for r in (fa.get("families") or {}).get(fam, []) if r["attribute"] != "prvdr_type"]


def build_tables(paths: Paths) -> list[dict]:
    best = evaluate.best_families(paths)
    parts = {p: evaluate.load_part(paths, p) or {} for p in evaluate.PARTS}
    stab = evaluate.load_part(paths, "stability") or {}
    out = []
    specs = [("T1_detection", "T1 Detection (pooled test years, cross-fitted, 95 % NPI-bootstrap CI)", t1_rows(paths)),
             ("T2_correctness", "T2 Correctness (medium intensity; injection models)",
              eval_report.t2_rows(parts["correctness"], best)),
             ("T3_consistency", "T3 Consistency (best GBM vs EBM / GA²M, both flag at k = 1 %)",
              eval_report.t3_rows(parts["consistency"], best)),
             ("T4_faithfulness_stability", "T4 Faithfulness and stability",
              eval_report.t4_rows(parts["faithfulness"], stab)),
             ("T5_sensitivity", "Sensitivity suite (E9)", sensitivity_rows(paths, best)),
             ("T6_fairness", "Fairness profile (E10), best GBM", fairness_rows(paths, best))]
    for name, title, rows in specs:
        if rows:
            out.append(write_table(paths, name, title, rows))
    return out


