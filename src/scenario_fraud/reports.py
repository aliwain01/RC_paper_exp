def build_figures(paths: Paths) -> dict:
    plt = _style()
    best = evaluate.best_families(paths)
    synthetic = bool(qa.data_provenance(paths)["synthetic"])
    out = {}
    for name, fn in FIGURES.items():
        fig = fn(paths, plt, best, synthetic)
        out[name] = _save(paths, fig, name, synthetic) if fig is not None else None
    return out


